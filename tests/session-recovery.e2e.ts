import {_electron as electron} from 'playwright';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {createInterface} from 'node:readline';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {Store} from '../app/store';
import type {Chat,Turn} from '../app/types';
import {Backend,PYTHON} from '../app/backend';
const root=path.resolve('.'),data=path.join(root,'work','session-recovery-'+Date.now());
await fs.mkdir(data,{recursive:true});
const store=new Store(path.join(data,'chat.sqlite')),project=store.project(data);
const empty=store.chat(project.id),used=store.chat(project.id);
for(const chat of [empty,used])store.update<Chat>('chat',chat.id,{storedId:'missing-'+chat.id});
const failed=store.accept(crypto.randomUUID(),empty.id,'Earlier failed first send');
store.update<Turn>('turn',failed.id,{status:'interrupted',error:'Provider credential was missing'});
const completed=store.accept(crypto.randomUUID(),used.id,'Earlier completed request');
store.update<Turn>('turn',completed.id,{status:'completed',text:'Saved answer'});store.db.close();
const records=path.join(data,'requests.jsonl');
const fake=spawn(PYTHON,['tests/fake_provider.py'],{cwd:root,env:{...process.env,FIXTURE_RECORDS:records},windowsHide:true,stdio:'pipe'});
fake.stderr.on('data',b=>process.stderr.write(b));
const lines=createInterface({input:fake.stdout});const [line]=await once(lines,'line');const {url}=JSON.parse(line);
const instance=await electron.launch({executablePath:process.env.TRISMEGISTUS_EXE,args:process.env.TRISMEGISTUS_EXE?[]:[root],env:{...process.env,TRISMEGISTUS_TEST_DATA:data,TRISMEGISTUS_TEST_PROVIDER_URL:url}});
const credential=new Backend(root,data,'Trismegistus/Test/'+path.basename(data),()=>{});
try{
 const page=await instance.firstWindow();
 const call=(method:string,args:any={})=>page.evaluate(({method,args})=>window.desktop.invoke(method,args),{method,args});
 const wait=async(fn:(s:any)=>boolean)=>{const until=Date.now()+90000;while(Date.now()<until){const s=await call('state');if(fn(s))return s;await page.waitForTimeout(150);}throw Error('Recovery timed out');};
 await wait(s=>s.backend==='ready');await call('saveKey',{key:'synthetic-deepseek-regression-credential'});
 await wait(s=>s.backend==='ready'&&s.connected);
 const id=crypto.randomUUID();await call('submit',{id,chatId:empty.id,text:'Recover this empty failed session',selected:true});
 const recovered=await wait(s=>s.turns.find((t:any)=>t.id===id)?.status==='completed');
 assert.equal(recovered.turns.find((t:any)=>t.id===failed.id).error,'Provider credential was missing');
 assert.notEqual(recovered.chats.find((c:any)=>c.id===empty.id).storedId,'missing-'+empty.id);
 const protectedId=crypto.randomUUID();await call('submit',{id:protectedId,chatId:used.id,text:'Do not silently discard prior work',selected:true});
 const protectedState=await wait(s=>s.turns.find((t:any)=>t.id===protectedId)?.status==='completed');
 assert.notEqual(protectedState.chats.find((c:any)=>c.id===used.id).storedId,'missing-'+used.id);
 assert.equal(protectedState.turns.find((t:any)=>t.id===completed.id).text,'Saved answer');
 const requests=(await fs.readFile(records,'utf8')).trim().split('\n').map(line=>JSON.parse(line));
 assert.match(JSON.stringify(requests.at(-1)),/Saved answer/);assert.match(JSON.stringify(requests.at(-1)),/Earlier completed request/);
 assert.doesNotMatch(JSON.stringify(requests.at(-1)),/Earlier failed first send/);
 console.log('PASS missing native sessions recover from durable chat history, retaining completed answers and chat isolation');
}finally{await instance.evaluate(({app})=>app.quit());await instance.close();fake.stdin.end('\n');lines.close();await credential.host('delete_key');}
