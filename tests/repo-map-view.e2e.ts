import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {chromium} from 'playwright';
import {pathToFileURL} from 'node:url';

const root=await fs.mkdtemp(path.resolve('work/repo-map-view-'));
const cli=path.resolve('hermes/skills/software-development/repo-map/scripts/cli.mjs');
await fs.mkdir(path.join(root,'src'));await fs.mkdir(path.join(root,'tests'));await fs.mkdir(path.join(root,'lib'));
await fs.writeFile(path.join(root,'lib/helper.ts'),'export function helper() {}\n');
await fs.writeFile(path.join(root,'src/voice.ts'),'export function transcribeVoice(input: string) {return input;}\n');
await fs.writeFile(path.join(root,'tests/voice.test.ts'),"import {transcribeVoice} from '../src/voice';\n");
const hostile='</script><script>globalThis.repoMapInjected=true</script><img src="https://invalid.example/probe" onerror="globalThis.repoMapInjected=true">';
await fs.writeFile(path.join(root,'REPO-MAP-NOTES.json'),JSON.stringify({claims:[{kind:'purpose',text:hostile,evidence:[]}]}));
execFileSync(process.execPath,[cli,root,'--html','--quiet'],{windowsHide:true});
await fs.access(path.join(root,'.repo-map/map.html'));
const browserTemp=path.join(root,'browser-temp');await fs.mkdir(browserTemp);process.env.TEMP=browserTemp;process.env.TMP=browserTemp;
const browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
try{
 const page=await browser.newPage({viewport:{width:1100,height:900},reducedMotion:'reduce'}),errors:string[]=[],network:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
 await page.clock.install();
 await page.goto(pathToFileURL(path.join(root,'.repo-map/map.html')).href);
 const floor=page.locator('.floor');
 assert.equal(await floor.count(),1,'The floor exists independently of the graph canvas');
 const floorState=()=>floor.evaluate(e=>({markup:e.outerHTML,bounds:e.getBoundingClientRect().toJSON(),transform:getComputedStyle(e).transform,display:getComputedStyle(e).display}));
 const fixedFloor=await floorState();assert.notEqual(fixedFloor.display,'none');
 const beforeZoom=await page.locator('canvas').evaluate(e=>(e as HTMLCanvasElement).toDataURL());
 await page.getByLabel('Map zoom',{exact:true}).focus();await page.keyboard.press('ArrowRight');
 assert.notEqual(await page.locator('canvas').evaluate(e=>(e as HTMLCanvasElement).toDataURL()),beforeZoom,'Zoom changes the graph');
 await page.getByRole('button',{name:'3D',exact:true}).click();await page.getByLabel('Rotate',{exact:true}).check();
 const graphBefore=await page.locator('canvas').evaluate(e=>(e as HTMLCanvasElement).toDataURL());
 await page.clock.runFor(1000);
 assert.notEqual(await page.locator('canvas').evaluate(e=>(e as HTMLCanvasElement).toDataURL()),graphBefore,'Graph actually rotates');
 assert.deepEqual(await floorState(),fixedFloor,'Rotation must not move or rebuild the floor');
 await page.getByLabel('Find map idea').fill('transcribe');
 await page.getByRole('button',{name:'src · 1 files',exact:true}).click();
 await page.getByRole('button',{name:/src\/voice.ts/}).click();
 assert.match(await page.locator('pre').innerText(),/transcribeVoice/);
 assert.match(await page.locator('pre').innerText(),/tests\/voice.test.ts/);
 await page.screenshot({path:path.join(root,'map.png')});
 await page.getByRole('button',{name:'2D',exact:true}).click();assert.equal(await page.getByLabel('Rotate',{exact:true}).isDisabled(),true);
 await page.getByLabel('Show all map areas').click();await page.getByLabel('Find map idea').fill('absentxyz');assert.equal(await page.getByText('No matches. Try a file or symbol name.').count(),1);
 assert.deepEqual(await floorState(),fixedFloor,'Drill-down, filtering and 2D keep the same stationary floor');
 assert.equal(await page.evaluate(()=>Reflect.get(globalThis,'repoMapInjected')),undefined);
 assert.equal(await page.locator('img').count(),0);
 await page.getByText('Scope, evidence and limitations',{exact:true}).click();
 assert.equal(await page.getByText(hostile,{exact:true}).count(),1);
 assert.equal(await page.getByText('purpose · unverified evidence',{exact:true}).count(),1);
 assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
 console.log('PASS offline view: modes, rotation, idea search, drill-down, reverse imports, hostile notes inert, no network. '+root);
}finally{await browser.close();}
