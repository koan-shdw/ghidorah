import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {createInterface} from 'node:readline';
import {once} from 'node:events';
import {runClaude} from '../app/claude';
import {SecretScrubber} from '../app/redaction';

const root=path.resolve('.'),scratch=await fs.mkdtemp(path.join(root,'work','claude-transport-'));
const scrubber=new SecretScrubber();scrubber.register('fixture-secret');
const base={executable:process.execPath,prefixArgs:[path.join(root,'tests/fixtures/claude-cli.mjs')],python:path.join(root,'runtime/python/cpython-3.12.10-windows-x86_64-none/python.exe'),worker:path.join(root,'backend/claude_worker.py'),directory:scratch,dataRoot:path.join(scratch,'private'),exchangeRoot:scratch,model:'fixture',effort:'high',mode:'manual' as const,hasFolder:true,scrubber};
let asked=0;
const run=async(spec:unknown,extra:Partial<Parameters<typeof runClaude>[0]>={})=>runClaude({...base,prompt:JSON.stringify(spec),signal:AbortSignal.timeout(15000),event:()=>{},approve:async()=>{asked++;return true;},...extra});
const target=path.join(scratch,'allowed.txt');
assert.equal((await run({action:'write',path:target})).status,'completed');
assert.equal(asked,1);assert.equal(await fs.readFile(target,'utf8'),'approved fixture');
const denied=path.join(scratch,'denied.txt');
await run({action:'write',path:denied},{approve:async()=>false});
assert.equal(await fs.access(denied).then(()=>true,()=>false),false);
await run({action:'write',path:denied},{approve:async()=>{throw Error('approval disconnected');}});
assert.equal(await fs.access(denied).then(()=>true,()=>false),false);
const secret=path.join(scratch,'.claude','fixture.txt');
await run({action:'write',path:secret},{mode:'bypass'});
assert.equal(asked,1);assert.equal(await fs.access(secret).then(()=>true,()=>false),false);
console.log('PASS protocol fixture: approval, denial, failed callback and fixed protection in Bypass');
await assert.rejects(run({action:'write',path:denied},{mode:'auto',model:'no-auto'}),/Auto is unavailable/);
assert.equal(await fs.access(denied).then(()=>true,()=>false),false);
console.log('PASS unsupported native mode is rejected before the user prompt or any tool action');
const events:any[]=[];
await run({action:'stream'},{event:event=>events.push(event)});
assert.doesNotMatch(JSON.stringify(events),/fixture-secret/);
assert.equal(events.filter(e=>e.type==='stream_event').map(e=>e.event.delta.text).join(''),'before [redacted] after');
console.log('PASS Claude split-stream secret redaction');
const abort=new AbortController();let childPid=0;
const stopped=await run({action:'cancel'},{signal:abort.signal,event:event=>{if(event.childPid){childPid=event.childPid;abort.abort();}}});
assert.equal(stopped.status,'stopped');assert.ok(childPid);
assert.throws(()=>process.kill(childPid,0));
console.log('PASS private-pipe cancellation stops the native child process tree');
assert.equal((await fs.readdir(scratch)).some(name=>name.startsWith('claude-')),false);
const host=spawn(process.execPath,['--import','tsx','tests/fixtures/claude-host.ts',JSON.stringify(base)],{cwd:root,windowsHide:true,stdio:'pipe'});
const lines=createInterface({input:host.stdout});
const [line]=await once(lines,'line');const orphanPid=JSON.parse(line).childPid;
host.kill('SIGKILL');await once(host,'close');
let alive=true;const deadline=Date.now()+10000;
while(alive&&Date.now()<deadline){try{process.kill(orphanPid,0);await new Promise(resolve=>setTimeout(resolve,100));}catch{alive=false;}}
assert.equal(alive,false);lines.close();
console.log('PASS app-host crash closes the lease and stops the Claude process tree');
